#!/usr/bin/env node
// Deterministic, source-only hydration for the exact NS-KB-21 schema.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { verifyDatasetIntegrity } from './ci/verify-dataset-integrity.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
verifyDatasetIntegrity(root);
const read = (path) => readFileSync(resolve(root, path), 'utf8');
const json = (path) => JSON.parse(read(path));
const hash = (body) => createHash('sha256').update(body).digest('hex');
const sql = (value) => value === null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const j = JSON.stringify;
const slug = s=>s.toLowerCase().replace(/&/g,'and').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const paths = {
  industry: 'content/taxonomy/master-32-industry-matrix.json',
  state: 'content/atlas/subnational-36states-fct-atlas.json',
  lga: 'content/atlas/lga-774-constitutional-registry.json',
  module: 'content/atlas/lga-14-service-modules-spec.json',
  evidence: 'content/atlas/evidence-sources.json',
  faq: 'content/canonical/reviewed-v2.1/faq.json',
  reviewedAnswers: 'content/canonical/reviewed-v2.1/answer-units.json',
  reviewedBindings: 'content/canonical/reviewed-v2.1/bindings.json',
  reviewedBenchmarks: 'content/canonical/reviewed-v2.1/benchmark-answer-overrides.json',
  routeGroups: 'content/taxonomy/route-groups.json',
  rag: 'content/canonical/rag-geo-aeo-15-benchmarks.json',
  schema: 'specs/schemas/json-schema-2020-12/LgaGovernanceServiceEnvelope.schema.json',
};
const sources = Object.values(paths).concat(readdirSync(resolve(root, 'specs/rfcs')).filter(p => /^NS-RFC-\d{3}.*\.md$/.test(p)).sort().map(p => `specs/rfcs/${p}`));
const lines = [
  '-- Generated by node scripts/generate-d1-seed.mjs; do not edit by hand.',
  '-- Source hashes identify repository bytes, not empirical verification or signed audit roots.',
  '-- Council codes are project identifiers, not official assigned administrative codes.',
  '-- Per-cell provenance remains canonical in the atlas JSON; this fixed D1 schema stores assessed-source URLs only.',
  '-- Unknown timestamps/metadata are empty strings; absent evidence arrays are []; readiness is NOT_ASSESSED.',
  '-- Candidate RFCs map to DRAFT_STANDARD. Industry evidence maps conservatively to UNRESOLVED.',
  ...sources.map(path => `-- source ${path} sha256=${hash(read(path))}`),
  'PRAGMA foreign_keys = ON;', 'BEGIN TRANSACTION;',
  "DELETE FROM ngstack_global_search_fts WHERE entity_type IN ('RFC','INDUSTRY','STATE','LGA','LGA_MODULE','FAQ','RAG_BENCHMARK');",
];
function insert(table, object, pointer, upsert = true) {
  lines.push(`-- source-pointer ${pointer}`);
  const columns = Object.keys(object);
  const conflict = upsert ? ` ON CONFLICT(${columns[0]}) DO UPDATE SET ${columns.slice(1).map(c => `${c}=excluded.${c}`).join(', ')}` : '';
  lines.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${Object.values(object).map(sql).join(', ')})${conflict};`);
}
function fts(type, id, url, title, body, tags, pointer) {
  insert('ngstack_global_search_fts', { entity_type: type, entity_id: id, canonical_url: url, title_civic: title, body_searchable: body, statutory_tags: tags }, pointer, false);
}
const plain = text => text.replaceAll('**', '').replaceAll('`', '').replace(/\\([.()&])/g, '$1').trim();
for (const path of sources.filter(p => p.startsWith('specs/rfcs/'))) {
  const body = read(path);
  const id = path.match(/NS-RFC-\d{3}/)[0];
  const title = plain(body.split('\n')[0].replace(/^#\s*/, '')).replace(/^\d+\.\s*NS-RFC-\d{3}:\s*/, '');
  const wg = body.match(/\*\*Working Group:\*\*\s*(WG-\d{2})/)?.[1];
  if (!wg || !body.includes('CANDIDATE STANDARD')) throw new Error(`Unmapped RFC metadata: ${path}`);
  const anchors = [...body.matchAll(/^\* \*\*Statutory (?:Anchor|Alignment):\*\* (.+)$/gm)].map(m => plain(m[1]));
  insert('normative_rfcs', { rfc_id: id, slug: path.split('/').at(-1).replace(/\.md$/, '').toLowerCase(), title, working_group: wg, status: 'DRAFT_STANDARD', hourglass_layer: '', statutory_anchors_json: j(anchors), summary_civic: title, full_markdown_body: body, openapi_contract_path: null, json_schema_uri: null, sha256_digest: hash(body), updated_at_utc: '' }, path);
  fts('RFC', id, `/rfcs/${id}`, title, body, anchors.join(' '), path);
}
const industries = json(paths.industry).industries;
for (const [index, row] of industries.entries()) {
  const pointer = `${paths.industry}#/industries/${index}`;
  insert('industry_capability_ledger', { industry_id: row.industryId, macro_sector: row.macroSector ?? '', industry_name: row.name, civic_bottleneck_summary: row.concreteFailureMode, primary_gap_mechanisms_json: j(row.residualGapMechanisms), building_blocks_json: j(row.nigeriaStackIntervention.buildingBlocks), protocols_json: j(row.nigeriaStackIntervention.protocols ?? []), evidence_confidence: 'UNRESOLVED', documented_incumbents_json: j(row.documentedDomesticSupply), statutory_regulators_json: j(row.statutoryStewards) }, pointer);
  fts('INDUSTRY', row.industryId, `/sectors/${slug(json(paths.routeGroups).groups.find(g=>g.industryIds.includes(row.industryId)).name)}/${row.industryId}`, row.name, `Source assertions; evidence unresolved. ${row.concreteFailureMode}`, row.statutoryStewards.join(' '), pointer);
}
const registry = json(paths.lga);
const atlas = json(paths.state);
const evidenceSources = json(paths.evidence).sources;
const statusMap = { VERIFIED_LIVE_PORTAL: 'LIVE_DIGITAL', CORROBORATED_PILOT: 'ACTIVE_PILOT', PAPER_BOUND_GAP: 'PAPER_ONLY', NOT_ASSESSED: 'NOT_ASSESSED', UNKNOWN: 'NOT_ASSESSED' };
const statusColumns = ['judiciary_status', 'land_registry_status', 'irs_treasury_status', 'health_shia_status', 'crvs_lga_status', 'open_contracting_status', 'agri_extension_status', 'fiber_row_hosting_status'];
if (registry.statesAndTerritory.length !== 37 || atlas.jurisdictions.length !== 37 || atlas.dimensions.length !== 8) throw new Error('State cardinality mismatch');
let lgaCount = 0;
const codes = new Set();
for (const [index, row] of registry.statesAndTerritory.entries()) {
  const atlasRow = atlas.jurisdictions.find(s => s.code === row.stateCode);
  if (!atlasRow || row.lgas.length !== row.lgaCount || atlas.dimensions.some(d => !atlasRow[d])) throw new Error(`Incomplete state ${row.stateCode}`);
  const pointer = `${paths.lga}#/statesAndTerritory/${index}`;
  const cells = atlas.dimensions.map(d => atlasRow.assessmentProvenance[d]);
  const assessedCells = cells.filter(c => !['NOT_ASSESSED', 'UNKNOWN'].includes(c.assessmentState));
  const assessedUrls = [...new Set(assessedCells.flatMap(c => c.sourceRefs.map(id => evidenceSources[id].url)))];
  const verifiedAt = assessedCells.length === 8 ? assessedCells.map(c => c.observedAt).sort().at(-1) : '';
  insert('subnational_state_atlas', { state_code: row.stateCode, state_name: row.stateName, capital_city: row.capital, geopolitical_zone: row.zone, lga_count: row.lgaCount, ...Object.fromEntries(statusColumns.map((c, i) => [c, statusMap[atlasRow[atlas.dimensions[i]]]])), primary_evidence_links_json: j(assessedUrls), last_verified_utc: verifiedAt }, `${pointer}; ${paths.state}#/jurisdictions/${atlas.jurisdictions.indexOf(atlasRow)}`);
  fts('STATE', row.stateCode, `/atlas/states/${row.stateCode}`, row.stateName, `${row.capital}; ${row.zone}; ${8 - assessedCells.length} readiness dimensions unknown or not yet assessed; ${assessedCells.length} assessed. Per-cell evidence scope and limitations are in the canonical atlas JSON.`, '', pointer);
}
for (const [index, row] of registry.statesAndTerritory.entries()) {
  for (const [lgaIndex, value] of row.lgas.entries()) {
    const colon = value.indexOf(':');
    const code = value.slice(0, colon), name = value.slice(colon + 1);
    if (colon < 0 || !code.startsWith(`${row.stateCode}-LGA-`) || codes.has(code)) throw new Error(`Invalid/duplicate LGA ${value}`);
    codes.add(code); lgaCount++;
    const pointer = `${paths.lga}#/statesAndTerritory/${index}/lgas/${lgaIndex}`;
    insert('constitutional_lga_774_registry', { lga_code: code, state_code: row.stateCode, lga_name: name, constitutional_schedule_ref: '1999 CFRN First Schedule Part I/II & Fourth Schedule', sc_cv_343_2024_direct_treasury_status: 'NOT_ASSESSED', kioskbase_offline_node_status: 'NOT_ASSESSED', active_lga_modules_json: '[]' }, pointer);
    fts('LGA', code, `/atlas/lga-774/${row.stateCode}/${code}`, name, `${row.stateName}; project council identifier, not official assigned code; council name corroboration and unresolved variants are recorded in canonical JSON. Treasury and offline node not yet assessed; no active deployments evidenced.`, '', pointer);
  }
}
const modules = json(paths.module).modules;
const moduleSchema = json(paths.schema);
for (const [index, row] of modules.entries()) {
  const pointer = `${paths.module}#/modules/${index}`;
  if (!moduleSchema.properties.moduleId.enum.includes(row.moduleId)) throw new Error(`Module schema mismatch ${row.moduleId}`);
  insert('lga_service_modules_14', { module_id: row.moduleId, route_slug: row.route, civic_service_name: row.canonicalName, protocol_tag: row.canonicalName, fourth_schedule_function: `Proposed legal mapping; external validation required. ${row.fourthScheduleMandate}`, target_persona_clusters_json: j(row.targetPersonaClusters), failure_mechanisms_resolved_json: j(row.gapMechanismsSolved), kioskbase_offline_capable: Number(row.channels.includes('KIOSKBASE_OFFLINE_PWA')), splitdirect_zero_escrow_enforced: 1, json_schema_pointer: moduleSchema.$id }, pointer);
  fts('LGA_MODULE', row.moduleId, row.route, row.canonicalName, `Proposed service specification. Legal mapping and claimed outcomes require external validation. No deployment attestation supplied.`, 'Proposed legal mapping', pointer);
}
for (const [index, row] of json(paths.faq).entries()) fts('FAQ', row.id, `/governance#${row.id}`, row.question, row.answer, 'Reviewed local copy; no deployment accreditation', `${paths.faq}#/${index}`);
const reviewedAnswers=json(paths.reviewedAnswers), bindings=json(paths.reviewedBindings), overrides=json(paths.reviewedBenchmarks);
for (const [index, row] of json(paths.rag).benchmarks.entries()) {
 const aliases=bindings.answerCrosswalk.filter(a=>a.renderWithRagId===row.benchmarkId).map(a=>reviewedAnswers.find(u=>u.id===a.answerId)).filter(Boolean);
 const body=aliases.length?aliases.map(a=>a.leadAnswer).join(' '):overrides[row.benchmarkId]||row.leadAnswerUnder65Words;
 fts('RAG_BENCHMARK', row.benchmarkId, `${row.boundRoute}#${row.benchmarkId}`, row.h2Heading, body, row.primarySources.join(' '), `${paths.rag}#/benchmarks/${index}; reviewed copy overrides are separately hashed`);
}
if (lgaCount !== 774 || industries.length !== 32 || modules.length !== 14) throw new Error('Canonical cardinality mismatch');
lines.push('-- No daily_merkle_audit_roots inserted: no signed production audit evidence supplied.', 'COMMIT;', '');
const output = lines.join('\n');
for (const path of ['scripts/seed-d1-from-canonical-json.sql', 'apps/web/scripts/seed-d1-from-canonical-json.sql']) writeFileSync(resolve(root, path), output);
console.log(j({ rfcs: 14, industries: industries.length, jurisdictions: 37, readinessCells: 296, lgas: lgaCount, modules: modules.length, faq: 15, benchmarks: 15, auditRootsInserted: 0, seedSha256: hash(output) }));
